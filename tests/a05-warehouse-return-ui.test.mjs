import test from 'node:test'
import assert from 'node:assert/strict'
import {readFile} from 'node:fs/promises'

const text=async path=>readFile(new URL('../'+path,import.meta.url),'utf8')

test('A05 single return entry point, with links but no duplicate return forms',async()=>{
 const wh=await text('app/warehouse/page.tsx')
 const stock=await text('app/stock/page.tsx')
 const returns=await text('app/warehouse/returns/page.tsx')
 const correction=await text('components/WarehouseCorrections.tsx')
 assert.doesNotMatch(wh,/import TechnicianWarehouseMovement/)
 assert.doesNotMatch(stock,/import TechnicianWarehouseMovement/)
 assert.match(returns,/import TechnicianWarehouseMovement/)
 assert.match(returns,/<TechnicianWarehouseMovement/)
 assert.match(wh,/href="\/warehouse\/returns"/)
 assert.match(stock,/href="\/warehouse\/returns"/)
 assert.doesNotMatch(correction,/returnVanStockToWarehouse/)
 assert.doesNotMatch(correction,/Confirm warehouse return/)
})
test('A05 van and warehouse selection is explicit; no first company van preselection',async()=>{
 const form=await text('components/TechnicianWarehouseMovement.tsx')
 const request=await text('components/WarehouseRequestForm.tsx')
 const wh=await text('app/warehouse/page.tsx')
 assert.match(form,/useState\(''\)/)
 assert.match(form,/<option value="">Select source van<\/option>/)
 assert.match(form,/<option value="">Select destination warehouse<\/option>/)
 assert.match(form,/ready=Boolean\(van&&warehouse&&product&&reference\.trim\(\)/)
 assert.doesNotMatch(form,/vans\?\.\[0\]|vans\[0\]|defaultVanId/)
 assert.match(request,/useState\(selectedVanId\?\?'\'\)/)
 assert.match(request,/Select receiving van/)
 assert.match(wh,/selectedVanId=\{null\}/)
})
test('A05 return is disabled and double submission is blocked on both client and server',async()=>{
 const form=await text('components/TechnicianWarehouseMovement.tsx')
 const corr=await text('components/WarehouseCorrections.tsx')
 const actions=await text('lib/actions.ts')
 assert.match(form,/!enabled\|\|!ready\|\|locked\.current\|\|pending\|\|completed/)
 assert.match(form,/locked\.current=true/)
 assert.match(form,/!enabled\?\(/)
 assert.match(form,/Warehouse stock movements unavailable/)
 assert.match(form,/Ready to confirm — review return/)
 assert.match(corr,/!enabled\?\(/)
 assert.match(corr,/Warehouse adjustments unavailable/)
 assert.match(actions,/if \(!warehouseWritesEnabled\(process\.env\.WAREHOUSE_WRITES_ENABLED\)\) return \{ error: 'Warehouse operations disabled\.' \}/)
 assert.match(actions,/getWarehouseReturnSourceVans/)
 assert.match(actions,/working\.vans\.filter\(v=>v\.id===working\.selectedId\)/)
 assert.match(actions,/if \(profile\.role==='technician'\)/)
})
